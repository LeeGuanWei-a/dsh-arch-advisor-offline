export function findDoc(q) {
  const k = norm(q);
  if (!k) return null;
  if (/^\d{1,2}$/.test(k)) {
    const n = Number(k);
    return DOCS.find((d) => d.no === n) || null;
  }
  const up = String(q || '').trim().toUpperCase();
  return DOCS.find((d) => d.abbr.toUpperCase() === up)
    || DOCS.find((d) => norm(d.title) === k)
    || DOCS.find((d) => norm(d.title).includes(k) && k.length >= 3)
    || null;
}

